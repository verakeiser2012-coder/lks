/**
 * Фраза по номеру экземпляра. Детерминированно: один и тот же номер
 * всегда даёт одну и ту же фразу, даже если список позже дополнят
 * в конец. Поэтому новые фразы добавлять ТОЛЬКО в конец списка —
 * вставка в середину сдвинет фразы у уже проданных вещей.
 */
function phraseForNumber(number) {
  const n = Math.max(1, Number(number) || 1);
  return PHRASES[(n - 1) % PHRASES.length];
}

