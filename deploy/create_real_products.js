const insert = db.prepare(`
  INSERT INTO products
    (name, slug, description, price, category_id, image, stock, is_active,
     lead_time, includes, dimensions, weight, material, care)
  VALUES (?, ?, ?, ?, ?, '', ?, 1, ?, ?, ?, ?, ?, ?)
`);

db.exec('BEGIN');
try {
  // Заглушки убираем: «Товар №1» на витрине хуже, чем пустая витрина
  const stubs = db.prepare("SELECT id, name FROM products WHERE name LIKE 'Товар №%'").all();
  for (const s of stubs) {
    db.prepare('DELETE FROM order_items WHERE product_id = ?').run(s.id);
    db.prepare('DELETE FROM products WHERE id = ?').run(s.id);
    console.log('удалена заглушка:', s.name);
  }

  for (const p of products) {
    const slug = slugify(p.name);
    if (db.prepare('SELECT 1 FROM products WHERE slug = ?').get(slug)) {
      console.log('уже есть, пропускаю:', p.name);
      continue;
    }
    // Остаток 999: изготовление под заказ, склад не ограничивает
    insert.run(
      p.name, slug, p.description, p.price, p.category_id, 999,
      p.lead_time, p.includes, p.dimensions, p.weight, p.material, p.care
    );
    console.log('создан:', p.name, '—', p.price + '₽');
  }
  db.exec('COMMIT');
} catch (err) {
  db.exec('ROLLBACK');
  throw err;
}

