const insertPost = db.prepare(`
  INSERT INTO social_posts (text, media_path, media_type, scheduled_at, status, news_hook, link_url, approved)
  VALUES (?, '', '', ?, 'scheduled', ?, ?, 0)
`);
const insertTarget = db.prepare('INSERT INTO social_post_targets (post_id, network_key) VALUES (?, ?)');

const created = [];
for (const post of posts) {
  const scheduledAt = `${post.date} 12:00:00`;
  const exists = db
    .prepare("SELECT id FROM social_posts WHERE scheduled_at = ? AND news_hook = ?")
    .get(scheduledAt, post.hook);
  if (exists) {
    console.log(`ПРОПУСК (уже есть): ${post.date} — ${post.hook}`);
    continue;
  }

  const info = insertPost.run(`${post.text}\n\n${TAGS}`, scheduledAt, post.hook, LINK);
  const postId = info.lastInsertRowid;
  for (const network of ['telegram', 'vk', 'news']) {
    insertTarget.run(postId, network);
  }
  created.push({ id: postId, date: post.date, hook: post.hook });
}

console.log(`\nСоздано постов: ${created.length}`);
for (const item of created) {
  console.log(`  #${item.id}  ${item.date} 12:00  ${item.hook}`);
}
