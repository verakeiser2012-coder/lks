const before = db.prepare('SELECT id, name, material FROM products WHERE slug = ?').get(slug);
if (!before) {
  console.error('Товар не найден:', slug);
  process.exit(1);
}

const sets = Object.keys(fields).map((k) => `${k} = @${k}`).join(', ');
const res = db.prepare(`UPDATE products SET ${sets} WHERE slug = @slug`).run({ ...fields, slug });
const after = db.prepare('SELECT id, name, weight, dimensions, material, care FROM products WHERE slug = ?').get(slug);
console.log('Обновлено строк:', res.changes);
console.log('Было:', before.material);
console.log('Стало:', after);
